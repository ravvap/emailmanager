-- ============================================================================
-- 1. Main Email Send Table (em_email_send)
-- ============================================================================
CREATE TABLE em_email_send (
    send_id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id                 BIGINT NOT NULL,
    template_version_id         BIGINT NOT NULL,
    template_name               VARCHAR(255) NOT NULL,
    from_identity_id            BIGINT NOT NULL,
    recipient_mode              VARCHAR(50) NOT NULL,

    -- Frozen content snapshot captured at submission
    frozen_subject              VARCHAR(1000) NOT NULL,
    frozen_body_html            TEXT NOT NULL,
    frozen_body_plain_text      TEXT,

    -- Query metadata for dynamic re-run at dispatch (DATA_SOURCE_QUERY)
    data_source_query_id        UUID,
    data_source_query_version   INTEGER,
    query_parameters_json       TEXT,

    -- Send lifecycle & metrics
    status                      VARCHAR(50) NOT NULL,
    total_recipients            INTEGER NOT NULL DEFAULT 0,
    external_recipients         INTEGER NOT NULL DEFAULT 0,
    delivered_count             INTEGER NOT NULL DEFAULT 0,
    failed_count                INTEGER NOT NULL DEFAULT 0,

    -- Maker / Checker & lifecycle timestamps
    submitted_by                VARCHAR(255) NOT NULL,
    submitted_at                TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by                 VARCHAR(255),
    reviewed_at                 TIMESTAMP WITH TIME ZONE,
    review_comments             VARCHAR(500),
    canceled_at                 TIMESTAMP WITH TIME ZONE,
    completed_at                TIMESTAMP WITH TIME ZONE,
    updated_at                  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_em_email_send_status CHECK (
        status IN (
            'PENDING_REVIEW',
            'REJECTED_BY_REVIEWER',
            'CANCELED',
            'QUEUED',
            'IN_PROGRESS',
            'COMPLETED'
        )
    ),
    CONSTRAINT chk_em_email_send_recipient_mode CHECK (
        recipient_mode IN (
            'CONTACT_DISTRIBUTION_LIST',
            'DATA_SOURCE_QUERY',
            'FILE_UPLOAD',
            'DEFINE_AT_SEND'
        )
    )
);

CREATE INDEX idx_em_email_send_submitted_by_at
    ON em_email_send (submitted_by, submitted_at DESC);

CREATE INDEX idx_em_email_send_approval_queue
    ON em_email_send (status, external_recipients, submitted_at DESC);

CREATE INDEX idx_em_email_send_template_id
    ON em_email_send (template_id);


-- ============================================================================
-- 2. Send Recipients & Per-Recipient Delivery Tracking (em_email_send_recipient)
-- ============================================================================
CREATE TABLE em_email_send_recipient (
    send_recipient_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    send_id                     BIGINT NOT NULL,
    contact_id                  BIGINT,
    recipient_name              VARCHAR(255),
    recipient_email             VARCHAR(320) NOT NULL,
    classification              VARCHAR(20) NOT NULL,
    merge_values_json           TEXT,

    -- Delivery & bounce tracking
    delivery_status             VARCHAR(30) NOT NULL,
    bounce_category             VARCHAR(20) NOT NULL DEFAULT 'NONE',
    failure_reason              VARCHAR(1000),
    retry_count                 INTEGER NOT NULL DEFAULT 0,
    flagged_for_contact_review  BOOLEAN NOT NULL DEFAULT FALSE,
    delivered_at                TIMESTAMP WITH TIME ZONE,

    CONSTRAINT fk_em_send_recipient_send
        FOREIGN KEY (send_id) REFERENCES em_email_send (send_id) ON DELETE CASCADE,
    CONSTRAINT chk_em_send_recipient_classification CHECK (
        classification IN ('INTERNAL', 'EXTERNAL')
    ),
    CONSTRAINT chk_em_send_recipient_delivery_status CHECK (
        delivery_status IN (
            'PENDING',
            'SENT',
            'DELIVERED',
            'RETRYING',
            'FAILED_PERMANENT',
            'SKIPPED_INVALID'
        )
    ),
    CONSTRAINT chk_em_send_recipient_bounce_category CHECK (
        bounce_category IN ('NONE', 'TEMPORARY', 'PERMANENT')
    )
);

CREATE INDEX idx_em_send_recipient_send_id
    ON em_email_send_recipient (send_id);

CREATE INDEX idx_em_send_recipient_send_status
    ON em_email_send_recipient (send_id, delivery_status);

CREATE INDEX idx_em_send_recipient_email_bounce
    ON em_email_send_recipient (LOWER(recipient_email), bounce_category);


-- ============================================================================
-- 3. Frozen Attachments Snapshot (em_email_send_attachment)
-- ============================================================================
CREATE TABLE em_email_send_attachment (
    send_attachment_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    send_id                     BIGINT NOT NULL,
    file_name                   VARCHAR(255) NOT NULL,
    file_extension              VARCHAR(50) NOT NULL,
    file_size_bytes             BIGINT NOT NULL,
    file_content                BYTEA NOT NULL,

    CONSTRAINT fk_em_send_attachment_send
        FOREIGN KEY (send_id) REFERENCES em_email_send (send_id) ON DELETE CASCADE
);

CREATE INDEX idx_em_send_attachment_send_id
    ON em_email_send_attachment (send_id);


-- ============================================================================
-- 4. Send Audit Log (em_email_send_audit_log)
-- ============================================================================
CREATE TABLE em_email_send_audit_log (
    audit_id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    send_id                     BIGINT NOT NULL,
    action                      VARCHAR(50) NOT NULL,
    performed_by                VARCHAR(255) NOT NULL,
    detail                      VARCHAR(1000),
    performed_at                TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_em_send_audit_send
        FOREIGN KEY (send_id) REFERENCES em_email_send (send_id) ON DELETE CASCADE
);

CREATE INDEX idx_em_send_audit_send_id
    ON em_email_send_audit_log (send_id, performed_at DESC);